-- Minimal disposable Supabase-like schema for CI migration contracts only.
-- This fixture is not applied to the connected ProjectX Supabase project.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;

CREATE SCHEMA auth;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY
);

CREATE TABLE public.payment_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id text NOT NULL UNIQUE,
  event_type text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  received_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.billing_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  provider text NOT NULL,
  provider_subscription_id text NOT NULL UNIQUE,
  status text NOT NULL,
  plan_key text NOT NULL,
  current_period_end timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.billing_entitlements (
  user_id uuid NOT NULL UNIQUE,
  plan_key text NOT NULL,
  status text NOT NULL,
  monthly_credits integer NOT NULL,
  provider text NOT NULL,
  provider_subscription_id text NOT NULL,
  period_end timestamptz,
  credits_used integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.payment_analytics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  event_name text NOT NULL,
  provider text NOT NULL,
  plan_key text,
  amount_paise bigint,
  currency text NOT NULL,
  external_id text,
  properties jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE public.analytics_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  event_name text NOT NULL,
  properties jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE public.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  action text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE public.projects (
  id uuid PRIMARY KEY,
  owner_id uuid NOT NULL,
  workspace_id uuid NOT NULL
);

CREATE TABLE public.workspace_members (
  workspace_id uuid NOT NULL,
  user_id uuid NOT NULL,
  role text NOT NULL,
  PRIMARY KEY (workspace_id, user_id)
);

CREATE TABLE public.job_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id uuid NOT NULL,
  user_id uuid NOT NULL,
  kind text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  max_attempts integer NOT NULL,
  timeout_seconds integer NOT NULL,
  status text NOT NULL DEFAULT 'queued',
  created_at timestamptz NOT NULL DEFAULT now()
);
